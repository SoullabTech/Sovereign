'use strict';
/**
 * JARVIS Desktop D-14 — Founder Presence Authentication (§5–§11 of the D-14
 * mandate) — DESIGN / PROOF SUBSTRATE, NOT PRODUCTION INTEGRATION.
 *
 * This module is deliberately isolated: nothing in scripts/builder/jarvis-*.mjs
 * or desktop-app/jarvis/* imports it, and it imports nothing from either. Its
 * only job is to prove — with real cryptography, not mocks — that a founder-
 * presence decision CAN be bound to (principal, role, gate_id, resolution_type,
 * challenge, expiry) such that the binding survives tampering, replay, wrong
 * principal, wrong role, and process restart. It is proof-of-architecture, not
 * the wired system.
 *
 * What this module does NOT do, on purpose (§17 of the mandate):
 *   - It does not touch jarvis-runtime.mjs's HTTP surface.
 *   - It does not touch jarvis-authority-channel.mjs (Unit 16) or
 *     jarvis-governance-gate.mjs (Unit 19) — see the D-14 record for why Unit
 *     16's instruction model does not itself supply gate-binding, and why this
 *     substrate cannot simply "reuse" it.
 *   - It never generates, stores, or transports a real founder private key.
 *     Key custody (Keychain / Secure Enclave / LocalAuthentication) is a live
 *     macOS integration this module cannot exercise headlessly — see the D-14
 *     record's OS-PRESENCE PROOF / LIVE LOCAL DEVICE PROOF REQUIRED split.
 *   - It implements no Electron IPC, no preload surface, no UI.
 *
 * §9 canonical signed payload (the "founder resolution assertion"):
 *   { v, domain, principal, role, gate_id, resolution_type, challenge_id,
 *     nonce, issued_at, expires_at, requested_authority_digest }
 * `domain` is fixed and versioned so a signature from this scheme can never be
 * mistaken for a signature meant for a different protocol (domain separation).
 */

import { sign as edSign, verify as edVerify, generateKeyPairSync, randomBytes, createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, renameSync, mkdirSync } from 'node:fs';
import path from 'node:path';

/** §9 — fixed, versioned domain tag. Never reused for a different signing purpose. */
export const DOMAIN = 'jarvis.desktop.founder_presence.gate_resolution.v1';

/** §12 — D-14 V1 ruling: APPROVE and REFUSE require identical authentication strength. */
export const PERMITTED_RESOLUTION_TYPES = Object.freeze(['APPROVE', 'REFUSE']);

/** §3 — V1 scope: FOUNDER only. Not exported as configurable — this is a ruling, not a default. */
export const V1_ROLE = 'FOUNDER';

const REFUSAL = Object.freeze({
  UNKNOWN_PRINCIPAL: 'UNKNOWN_PRINCIPAL',
  UNKNOWN_CHALLENGE: 'UNKNOWN_CHALLENGE',
  CHALLENGE_CONSUMED: 'CHALLENGE_CONSUMED',
  CHALLENGE_EXPIRED: 'CHALLENGE_EXPIRED',
  CHALLENGE_MISMATCH: 'CHALLENGE_MISMATCH',
  DOMAIN_MISMATCH: 'DOMAIN_MISMATCH',
  ROLE_NOT_PERMITTED: 'ROLE_NOT_PERMITTED',
  RESOLUTION_TYPE_INVALID: 'RESOLUTION_TYPE_INVALID',
  SIGNATURE_INVALID: 'SIGNATURE_INVALID',
  PAYLOAD_MALFORMED: 'PAYLOAD_MALFORMED',
});
export { REFUSAL };

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);

function writeAtomic(dir, file, text) {
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  const tmp = `${file}.tmp-${process.pid}-${randomBytes(4).toString('hex')}`;
  writeFileSync(tmp, text);
  renameSync(tmp, file);
}

/**
 * §7 cryptographic identity — proof substrate uses Ed25519 (small, fast,
 * misuse-resistant, natively supported by Node's `crypto` and by the Secure
 * Enclave / CryptoKit family on macOS, which is the real target for the
 * eventual key). Generated here only to exercise the math: the real founder
 * key is never generated by, or passed through, this module in production.
 */
export function generateFounderKeypair() {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');
  return {
    publicKeyPem: publicKey.export({ type: 'spki', format: 'pem' }),
    privateKeyPem: privateKey.export({ type: 'pkcs8', format: 'pem' }),
  };
}

/** §9 — deterministic canonical bytes for the payload. Sorted keys, no ambiguity. */
export function canonicalize(payload) {
  const keys = Object.keys(payload).sort();
  const sorted = {};
  for (const k of keys) sorted[k] = payload[k];
  return Buffer.from(`${DOMAIN}\n${JSON.stringify(sorted)}`, 'utf8');
}

export function digest(value) {
  return createHash('sha256').update(JSON.stringify(value ?? null)).digest('hex');
}

/**
 * A minimal, file-persisted, single-use challenge ledger — standing in for
 * where the real runtime would mint and track challenges (§10, §11: P11 —
 * a challenge must not be reusable after a process restart if persistence is
 * required, which V1 requires). Reloading from disk in a fresh process must
 * see the same consumed state; this is exercised directly in the proof file.
 */
export function createChallengeLedger(dir) {
  const file = path.join(dir, 'challenges.json');
  const load = () => (existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {});
  const save = (state) => writeAtomic(dir, file, JSON.stringify(state, null, 2));

  return {
    /** Runtime mints a challenge bound to one gate/run/resolution intent. */
    issue({ gate_id, run_id = null, principal, role, permitted_resolution_types = PERMITTED_RESOLUTION_TYPES,
      requested_authority_digest = null, ttlMs = 120_000 }, now = new Date()) {
      const state = load();
      const challenge_id = `chal-${randomBytes(8).toString('hex')}`;
      const nonce = randomBytes(16).toString('hex');
      const issued_at = now.toISOString();
      const expires_at = new Date(now.getTime() + ttlMs).toISOString();
      state[challenge_id] = {
        challenge_id, gate_id, run_id, principal, role, permitted_resolution_types,
        requested_authority_digest, nonce, issued_at, expires_at, consumed: false, consumed_at: null,
      };
      save(state);
      return state[challenge_id];
    },

    get(challenge_id) {
      const state = load();
      return state[challenge_id] ?? null;
    },

    /** Single-use: marks CONSUMED. A second call for the same id is a no-op that reports already-consumed. */
    consume(challenge_id, now = new Date()) {
      const state = load();
      const c = state[challenge_id];
      if (!c) return { ok: false, refusal: REFUSAL.UNKNOWN_CHALLENGE };
      if (c.consumed) return { ok: false, refusal: REFUSAL.CHALLENGE_CONSUMED };
      c.consumed = true;
      c.consumed_at = now.toISOString();
      save(state);
      return { ok: true, challenge: c };
    },
  };
}

/**
 * §14/§15 — the Desktop-side act: build the exact bytes a founder-bound key
 * must sign. Desktop calls this with data it read from the runtime's challenge
 * response and the founder's explicit APPROVE/REFUSE choice — it never
 * constructs a payload the runtime did not first offer via a live challenge.
 */
export function buildAssertionPayload({ principal, role, gate_id, resolution_type, challenge_id, nonce,
  issued_at, expires_at, requested_authority_digest }) {
  if (!PERMITTED_RESOLUTION_TYPES.includes(resolution_type)) {
    throw Object.assign(new Error(REFUSAL.RESOLUTION_TYPE_INVALID), { code: REFUSAL.RESOLUTION_TYPE_INVALID });
  }
  return { v: 1, domain: DOMAIN, principal, role, gate_id, resolution_type, challenge_id, nonce,
    issued_at, expires_at, requested_authority_digest: requested_authority_digest ?? null };
}

/** Sign a payload with the founder's private key. In production this call happens
 *  only after OS-level presence (Touch ID / password) unlocks key use — that gate
 *  is outside what this module can exercise (see the D-14 record). Ed25519 has no
 *  incremental digest step; Node's `crypto.sign(null, ...)` is the correct API. */
export function signAssertion(payload, privateKeyPem) {
  const bytes = canonicalize(payload);
  const signature = edSign(null, bytes, privateKeyPem).toString('base64');
  return { payload, signature };
}

/**
 * §11 — the ONLY accept path. This stands in for the runtime's independent
 * re-verification: it re-derives everything from the challenge ledger and the
 * enrolled public key, and trusts NOTHING the caller asserts about itself
 * beyond the signature it can independently check.
 *
 * @param assertion { payload, signature }
 * @param opts { ledger, enrolledFounders: Map<principal, publicKeyPem>, gate: { gate_id, required_resolver_role, requested_authority_digest } }
 */
export function verifyFounderResolution(assertion, { ledger, enrolledFounders, gate }, now = new Date()) {
  const deny = (refusal, reason) => ({ ok: false, refusal, reason });
  if (!isObj(assertion) || !isObj(assertion.payload) || typeof assertion.signature !== 'string') {
    return deny(REFUSAL.PAYLOAD_MALFORMED, 'assertion must carry { payload, signature }');
  }
  const p = assertion.payload;
  if (p.domain !== DOMAIN) return deny(REFUSAL.DOMAIN_MISMATCH, `expected domain ${DOMAIN}`);

  const pub = enrolledFounders.get(p.principal);
  if (!pub) return deny(REFUSAL.UNKNOWN_PRINCIPAL, `'${p.principal}' is not an enrolled founder principal`);

  // Signature check FIRST and independently — nothing below this line is
  // trusted until the bytes are proven to have been signed by the enrolled key.
  // canonicalize() is re-derived from p here, never taken on trust from the
  // caller, so a tampered field changes the bytes verified, not just the field.
  let sigOk = false;
  try {
    const bytes = canonicalize(p);
    sigOk = edVerify(null, bytes, pub, Buffer.from(assertion.signature, 'base64'));
  } catch { sigOk = false; }
  if (!sigOk) return deny(REFUSAL.SIGNATURE_INVALID, 'signature does not verify against the enrolled founder key');

  if (p.role !== V1_ROLE || p.role !== gate.required_resolver_role) {
    return deny(REFUSAL.ROLE_NOT_PERMITTED, `gate requires ${gate.required_resolver_role}; assertion carries ${p.role}`);
  }
  if (!PERMITTED_RESOLUTION_TYPES.includes(p.resolution_type)) {
    return deny(REFUSAL.RESOLUTION_TYPE_INVALID, `'${p.resolution_type}' is not a permitted resolution type`);
  }
  if (p.gate_id !== gate.gate_id) {
    return deny(REFUSAL.CHALLENGE_MISMATCH, 'assertion is not bound to this gate');
  }
  if (gate.requested_authority_digest != null && p.requested_authority_digest !== gate.requested_authority_digest) {
    return deny(REFUSAL.CHALLENGE_MISMATCH, 'requested authority does not match what the gate actually asked for');
  }

  const c = ledger.get(p.challenge_id);
  if (!c) return deny(REFUSAL.UNKNOWN_CHALLENGE, 'no such challenge');
  if (c.gate_id !== p.gate_id) return deny(REFUSAL.CHALLENGE_MISMATCH, 'challenge was not issued for this gate');
  if (c.nonce !== p.nonce) return deny(REFUSAL.CHALLENGE_MISMATCH, 'nonce does not match the issued challenge');
  if (c.principal !== p.principal) return deny(REFUSAL.CHALLENGE_MISMATCH, 'challenge was not issued to this principal');
  if (Date.parse(p.expires_at) <= now.getTime()) return deny(REFUSAL.CHALLENGE_EXPIRED, `expired at ${p.expires_at}`);
  if (c.consumed) return deny(REFUSAL.CHALLENGE_CONSUMED, 'this challenge has already produced a resolution');

  const consumeResult = ledger.consume(p.challenge_id, now);
  if (!consumeResult.ok) return deny(consumeResult.refusal, 'challenge could not be consumed (race or already used)');

  return { ok: true, principal: p.principal, role: p.role, gate_id: p.gate_id, resolution_type: p.resolution_type,
    challenge_id: p.challenge_id, verified_at: now.toISOString() };
}
