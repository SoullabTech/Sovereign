#!/usr/bin/env bash
# Scaffold an Environmental Field Study sitting.
#
#   bash scripts/field-study-scaffold.sh now-what
#   bash scripts/field-study-scaffold.sh now-what --verify
#
# Method: docs/specs/developmental-environment/FIELD_STUDY_METHOD_CANDIDATE_2026-07-29.md
#
# The Observation Declaration is immutable for the sitting. --verify re-fingerprints the
# build and reports whether it changed underneath the study. Written for bash 3.2 (macOS).

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

FIELD="${1:-}"
MODE="${2:-scaffold}"

if [ -z "$FIELD" ]; then
  echo "usage: bash scripts/field-study-scaffold.sh <field-slug> [--verify]" >&2
  echo "  e.g. bash scripts/field-study-scaffold.sh now-what" >&2
  exit 2
fi

DATE="$(date +%F)"
STUDY_DIR="docs/field-studies/${FIELD}/${DATE}"
DECL="${STUDY_DIR}/OBSERVATION_DECLARATION.md"

# ---------------------------------------------------------------------------
# Two independent integrity declarations
#
#   1. OBSERVED BUILD  — did the product under study change during the sitting?
#   2. STUDY INSTRUMENT — did the method or harness change during the sitting?
#
# These are separate problems. The product can hold still while the method moves
# underneath it. Excluding study output prevents self-contamination; it does not
# detect someone editing SKILL.md or this script halfway through a sitting.
# ---------------------------------------------------------------------------

# NARROW BY RULING. Only the designated study-output directory is excluded, because it is
# generated by the observation process itself. Do NOT generalize this to documentation,
# reports, temp files, or "known harmless" paths — a curated exclusion list turns the
# fingerprint from a detector of drift into an opinion about drift.
EXCLUDE_RULE='docs/field-studies/'
EXCLUDE_WHY='generated by the observation process itself; scaffolding a sitting must not register as drift in the build the sitting observes'

# The method and its harness. Editing any of these mid-sitting invalidates the instrument.
INSTRUMENT_FILES="scripts/field-study-scaffold.sh
.claude/skills/field-study/SKILL.md
docs/specs/developmental-environment/FIELD_STUDY_METHOD_CANDIDATE_2026-07-29.md"

build_fingerprint() {
  local sha branch dirty tree status
  sha="$(git rev-parse --short HEAD)"
  branch="$(git rev-parse --abbrev-ref HEAD)"
  status="$(git status --porcelain | grep -v "$EXCLUDE_RULE" || true)"
  dirty="$(printf '%s\n' "$status" | grep -c . || true)"
  tree="$(printf '%s\n' "$status" | shasum | cut -c1-12)"
  echo "${sha}|${branch}|${dirty}|${tree}"
}

# Content hash, not git state — an uncommitted instrument is still a fixed instrument
# for the duration of a sitting, and must be detectable if it moves.
instrument_fingerprint() {
  printf '%s\n' "$INSTRUMENT_FILES" | while IFS= read -r f; do
    [ -n "$f" ] && shasum "$f" 2>/dev/null || echo "MISSING $f"
  done | shasum | cut -c1-12
}

instrument_rev() {
  local rev
  rev="$(printf '%s\n' "$INSTRUMENT_FILES" | tr '\n' ' ' | xargs git log -1 --format=%h -- 2>/dev/null || true)"
  [ -n "$rev" ] || rev="none"
  if printf '%s\n' "$INSTRUMENT_FILES" | while IFS= read -r f; do
       [ -n "$f" ] && git status --porcelain -- "$f"; done | grep -q .; then
    echo "${rev} (UNCOMMITTED — instrument is not yet fixed by a commit)"
  else
    echo "${rev}"
  fi
}

FP="$(build_fingerprint)"
FP_SHA="$(echo "$FP" | cut -d'|' -f1)"
FP_BRANCH="$(echo "$FP" | cut -d'|' -f2)"
FP_DIRTY="$(echo "$FP" | cut -d'|' -f3)"
FP_TREE="$(echo "$FP" | cut -d'|' -f4)"
IFP="$(instrument_fingerprint)"
IREV="$(instrument_rev)"

# ---------------------------------------------------------------------------
# --verify : did the build change underneath the sitting?
# ---------------------------------------------------------------------------
if [ "$MODE" = "--verify" ]; then
  if [ ! -f "$DECL" ]; then
    echo "no declaration at ${DECL} — nothing to verify" >&2
    exit 1
  fi
  DECLARED_SHA="$(grep '^- \*\*Commit:\*\*' "$DECL" | sed 's/.*`\(.*\)`.*/\1/' || true)"
  DECLARED_TREE="$(grep '^- \*\*Working-tree fingerprint:\*\*' "$DECL" | sed 's/.*`\(.*\)`.*/\1/' || true)"
  DECLARED_INST="$(grep '^- \*\*Instrument fingerprint:\*\*' "$DECL" | sed 's/.*`\(.*\)`.*/\1/' || true)"

  BUILD_OK=1; INST_OK=1
  [ "$DECLARED_SHA" = "$FP_SHA" ] && [ "$DECLARED_TREE" = "$FP_TREE" ] || BUILD_OK=0
  [ "$DECLARED_INST" = "$IFP" ] || INST_OK=0

  echo "=== Close report — ${FIELD} ${DATE} ==============================="
  echo
  echo "1. OBSERVED BUILD   (the product under study)"
  echo "   declared : ${DECLARED_SHA} / tree ${DECLARED_TREE}"
  echo "   current  : ${FP_SHA} / tree ${FP_TREE}"
  if [ "$BUILD_OK" = "1" ]; then
    echo "   INTACT — every observation belongs to the declared build."
  else
    echo "   DIVERGED — the product changed during the sitting."
  fi
  echo
  echo "2. STUDY INSTRUMENT (the method and harness)"
  echo "   declared : ${DECLARED_INST}"
  echo "   current  : ${IFP}"
  if [ "$INST_OK" = "1" ]; then
    echo "   INTACT — the method did not move under the sitting."
  else
    echo "   DIVERGED — the method or harness was edited mid-sitting."
  fi
  echo
  echo "Exclusion rule in force: '${EXCLUDE_RULE}'"
  echo "=================================================================="

  if [ "$BUILD_OK" = "1" ] && [ "$INST_OK" = "1" ]; then
    exit 0
  fi

  echo
  echo "Divergence is a REPORTABLE CONDITION, not a failure. Record both lines above in"
  echo "the Method Integrity page. Observations from before and after a divergence belong"
  echo "to different builds — or to different methods — and may not be compared."
  echo "Prefer re-walking to silently mixing evidence."

  if [ "$BUILD_OK" = "0" ] && [ "$INST_OK" = "0" ]; then exit 5; fi
  if [ "$BUILD_OK" = "0" ]; then exit 3; fi
  exit 4
fi

# ---------------------------------------------------------------------------
# scaffold
# ---------------------------------------------------------------------------
if [ -d "$STUDY_DIR" ]; then
  echo "study already scaffolded: ${STUDY_DIR}" >&2
  echo "(a sitting is scoped to one build; use --verify to check it is still intact)" >&2
  exit 1
fi

mkdir -p "$STUDY_DIR"

cat > "$DECL" <<EOF
