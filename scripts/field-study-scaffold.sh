# Emerging Patterns

Recurring structures independently observed **across** studies. The bridge between individual
field studies and future constitutional rulings — so that each study does not begin from zero.

```text
Pattern candidate 001
Continuity is strongest when the environment returns people to unfinished work
rather than to a chronological feed.

Observed in:      Now What? · Journal · Author Studio
Surfaced by:      temporal gravity · transition study · learning ecology
Observer:         single / independent
Status:           Candidate
```

## Two epistemic guards

**1. Same instrument ≠ convergent evidence.** A pattern surfaced in three fields by the *same*
instrument may be the shape of the instrument, not of the environments. Record which instrument
surfaced each occurrence. Cross-instrument convergence is strong; single-instrument recurrence
is weak.

**2. Priming contaminates accumulation.** A study run with knowledge of prior pattern candidates
will find them. This is a real tension in the method itself: *accumulation* (don't start from
zero) works against *independence* (don't confirm yourself). Provisional rule — instruments run
blind to the pattern register; only synthesis consults it, and says that it did.
EOF

