- **Walked** (observed directly in a running application):
  - <!-- route — viewport(s) — member state -->
- **Read** (implementation only):
  - <!-- route — why it could not be walked -->
- **Unavailable** (cannot currently be verified):
  - <!-- e.g. states requiring an invitation this observer may not mint -->
- **Needs production verification:**
  - <!-- -->

## Known divergence from production

<!-- If the studied build is not what members meet, say exactly how it differs.
     "Fixed on trunk" is not "live in production." -->

## Study ethics declaration

- Member content read: **none** / <!-- named consent basis -->
- Sanctuary content: **categorically excluded**
- Evidence deliberately foregone (and the conclusions left provisional as a result):
  - <!-- -->
EOF

