## Fingerprint algorithm and exclusions

Recorded so that a later reader can reproduce or challenge it.

- **Observed build:** \`git rev-parse --short HEAD\` + \`git rev-parse --abbrev-ref HEAD\` +
  \`git status --porcelain\` filtered through the exclusion rule below, hashed with
  \`shasum\`, truncated to 12 chars.
- **Study instrument:** \`shasum\` of each instrument file, hashed again, truncated to 12 chars.
  Content-based, not git-based — an uncommitted instrument is still fixed for the sitting.
- **Exclusion rule (the ONLY one):** \`${EXCLUDE_RULE}\`
- **Why excluded:** ${EXCLUDE_WHY}

**Narrowness is load-bearing.** No other path may be excluded — not documentation, not
reports, not temporary files, not "known harmless" changes. A curated exclusion list turns
the fingerprint from a detector of drift into an opinion about drift.

