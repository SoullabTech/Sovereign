#!/usr/bin/env node
/**
 * Writer's Studio — recovery run.
 *
 *   node scripts/writers-studio/recover-material.mjs \
 *     --manifest scripts/writers-studio/works/elemental-alchemy-ch10.json \
 *     --source docs/book-studio/sources/SPIRALOGIC_CHAPTER_9_ORIGINAL.md \
 *     [--out docs/book-studio/CHAPTER_10_RECOVERY_CANDIDATES_v1.md]
 *
 * Reads a recovery source against the fixture, reports what was lost and which
 * failing finding each loss would serve. Recommends nothing on its own
 * authority; writes only to --out.
 */
import { writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadDoctrine, readWorkReferent, analyze } from './developmental-editor.mjs';
import { readSource, recoveryCandidates, rankCandidates, SURVIVAL } from './recovery-lens.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const arg = (n, d = null) => { const i = process.argv.indexOf(`--${n}`); return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : d; };

const manifest = JSON.parse(readFileSync(path.resolve(repoRoot, arg('manifest')), 'utf8'));
const doctrine = loadDoctrine(path.resolve(repoRoot, 'scripts/writers-studio/doctrine', `${manifest.doctrine}.json`));
const fx = manifest.fixture_referent;
const fixture = readWorkReferent({ artifact: path.resolve(repoRoot, fx.artifact), fromLine: fx.fromLine, toLine: fx.toLine, label: fx.label });
const analysis = analyze(fixture, doctrine);

const srcPath = path.resolve(repoRoot, arg('source'));
const source = readSource(srcPath, path.basename(srcPath));
const ranked = rankCandidates(recoveryCandidates(source, fixture, doctrine, analysis.findings));

const absent = ranked.filter((c) => c.state === SURVIVAL.ABSENT);
const serving = absent.filter((c) => c.repairs.length && !c.pitch);
const livedOnly = absent.filter((c) => !c.repairs.length && c.lived && !c.pitch);
const pitch = absent.filter((c) => c.pitch);

const L = [];
L.push('# Chapter 10 — Recovery Candidates');
L.push('');
L.push(`> Generated by \`scripts/writers-studio/recover-material.mjs\`. Deterministic: survival is measured by 6-gram overlap, not judgement.`);
L.push('>');
L.push(`> **Recovery source** \`${path.relative(repoRoot, srcPath)}\` — sha256 \`${source.sha256.slice(0, 12)}\``);
L.push(`> **Fixture** \`${fx.label}\` — \`${fx.artifact}\` L${fx.fromLine}–${fx.toLine}`);
L.push(`> **Work referent** ${manifest.work_referent?.status ?? 'UNRESOLVED / OUT OF SCOPE'} — neither artifact is declared the Work.`);
L.push('');
L.push('**⛔ Absent is not a verdict.** Material is often cut for good reason. Every row below is an OBSERVATION: what was lost, and what it would serve. The author decides. The lens also names what it thinks should *not* come back.');
L.push('');
L.push(`Scanned ${ranked.length + 0} qualifying passages · **${absent.length} absent** from the fixture · ${serving.length} would serve a finding the fixture currently fails.`);
L.push('');

const row = (c) => {
  L.push(`### L${c.line} — ${c.lived ? '**lived**' : 'expository'}${c.elements.length ? ` · ${c.elements.join(' → ')}${c.returns ? ` (${c.returns} return${c.returns > 1 ? 's' : ''})` : ''}` : ''}`);
  L.push('');
  L.push(`> ${c.excerpt}`);
  L.push('');
  for (const s of c.serves) L.push(`- **serves \`${s.rule}\`** — ${s.why}`);
  if (c.markers.length) L.push(`- evidence: ${c.markers.join('; ')}`);
  L.push(`- survival in fixture: ${(c.survival * 100).toFixed(1)}%`);
  L.push('');
};

L.push('---');
L.push('');
L.push('## 1. Repairs a defect the fixture actually has');
L.push('');
if (!serving.length) L.push('_None._'); else serving.forEach(row);
L.push('## 2. Lived material lost, serving no current finding');
L.push('');
L.push('_Recovery value is editorial, not diagnostic — these are scenes, not repairs._');
L.push('');
if (!livedOnly.length) L.push('_None._'); else livedOnly.slice(0, 8).forEach(row);
if (livedOnly.length > 8) L.push(`_…and ${livedOnly.length - 8} more lived passages not listed._`, '');
L.push('## 3. Do NOT recover — pitch register');
L.push('');
L.push('_Absent from the fixture and flagged `D9.pitch-register` by the doctrine. Losing these was correct._');
L.push('');
for (const c of pitch.slice(0, 6)) { L.push(`- **L${c.line}** — ${c.excerpt}`); }
L.push('');

const outPath = path.resolve(repoRoot, arg('out', 'docs/book-studio/CHAPTER_10_RECOVERY_CANDIDATES_v1.md'));
writeFileSync(outPath, L.join('\n'));
console.log(`WROTE ${path.relative(repoRoot, outPath)}`);
console.log(`  absent=${absent.length}  serves-a-failing-finding=${serving.length}  lived-only=${livedOnly.length}  do-not-recover=${pitch.length}`);
for (const c of serving) console.log(`  L${String(c.line).padEnd(5)} ${c.repairs.map((s) => s.rule).join(',')}  ${c.excerpt.slice(0, 70)}`);
