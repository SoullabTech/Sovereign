import type { BenchmarkQuery, EvidenceLabel, GoldSource } from './scoring';

export type LaneExpectation = 'analytic' | 'associative' | 'bilateral';

export interface GoldBenchmarkQuery extends BenchmarkQuery {
  laneExpectation: LaneExpectation;
  rationale: string;
  expectedEmpty?: boolean;
  aperture?: {
    admitted?: string[];
    forbidden?: string[];
  };
  ablationCritical?: string[];
}

type GoldSpec = [sourceRef: string, labels: EvidenceLabel[], sourceClass?: string];

function g(sourceRef: string, labels: EvidenceLabel[], sourceClass = 'unknown'): GoldSource {
  return { sourceRef, labels, sourceClass };
}

function q(
  id: string,
  family: GoldBenchmarkQuery['family'],
  laneExpectation: LaneExpectation,
  query: string,
  gold: GoldSpec[],
  rationale: string,
  extra: Partial<GoldBenchmarkQuery> = {},
): GoldBenchmarkQuery {
  return {
    id, family, laneExpectation, query,
    gold: gold.map(([ref, labels, sourceClass]) => g(ref, labels, sourceClass)),
    rationale,
    ...extra,
  };
}
